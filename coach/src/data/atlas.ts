/** Ćwiczenia z atlasu, których jeszcze nie ma w bibliotece (porównanie bez wielkości liter). */
export function missingFromAtlas(names: string[]): [string, ExerciseCategory][] {
  const have = new Set(names.map((n) => n.trim().toLowerCase()));
  return ATLAS.filter(([n]) => !have.has(n.toLowerCase()));
}
